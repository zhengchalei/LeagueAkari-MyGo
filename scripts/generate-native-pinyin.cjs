const literals = {};
function literal(node) {
  if (ts.isStringLiteral(node)) return node.text;
  if (ts.isArrayLiteralExpression(node)) return node.elements.map(literal);
  if (ts.isObjectLiteralExpression(node)) return Object.fromEntries(node.properties.map(p => {
    if (!ts.isPropertyAssignment(p)) throw new Error('Unexpected dictionary syntax');
    return [ts.isStringLiteral(p.name) ? p.name.text : p.name.getText(ast), literal(p.initializer)];
  }));
  throw new Error('Dictionary is not a static literal');
}
function visit(node) {
  if (ts.isVariableDeclaration(node) && ts.isIdentifier(node.name) && node.initializer && ts.isObjectLiteralExpression(node.initializer)) {
    if (['v', 'P', 'S', 'T', '$', 'b', 'x'].includes(node.name.text)) literals[node.name.text] = literal(node.initializer);
  }
  ts.forEachChild(node, visit);
}
