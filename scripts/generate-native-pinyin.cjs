function noTone(value) {
  return value.replace(/[āáǎà]/g, 'a').replace(/[ōóǒò]/g, 'o').replace(/[ēéěè]/g, 'e').replace(/[īíǐì]/g, 'i').replace(/[ūúǔù]/g, 'u').replace(/[ǖǘǚǜ]/g, 'ü').replace(/n̄|ń|ň|ǹ/g, 'n').replace(/m̄|ḿ|m̌|m̀/g, 'm').replace(/ê̄|ế|ê̌|ề/g, 'ê');
}
